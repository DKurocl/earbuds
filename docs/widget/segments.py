"""Generates the widget's mode buttons: segment shapes that morph, and the layouts that use them.

    python3 docs/widget/segments.py

Why segments: a widget can't animate a GradientDrawable's corners, and a single vector stretched
to a button would distort them. So each button is three images in a row: a left cap, a stretching
middle and a right cap. A cap is exactly half as wide as the button is tall (adjustViewBounds keeps
its 1:2 ratio), so its vector scales uniformly and the corners stay true circles at every size.

Each image is an animated-selector on the button's enabled state. The chosen mode is disabled
(tapping it again does nothing anyway), so a change animates only when the state really changes:
the launcher can re-apply the same update any number of times without replaying anything. On
the change the caps morph their corners from the connected-group shape (outer corners round,
inner 16 of 64) to a full pill and back, and every part blends its color with the same timing.
Icon and label exist twice, in the off and on colors, and cross-fade through state list animators
(res/animator/w_while_*.xml) in step with the fill, so they never sit on the wrong background.
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res"
K = 0.44772  # 1 - 0.55228: cubic control offset for a quarter circle
W, H = 50.0, 100.0  # cap viewport: half the button height wide, the height tall
OUTER = 50.0  # full round
INNER = 100 * 16 / 64  # 16 dp on the dashboard's 64 dp buttons, as in the app; scales with height
MORPH_MS, COLOR_MS = 350, 250
EMPHASIZED = "@interpolator/w_emphasized"
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by docs/widget/segments.py; edit the script, not this file. -->\n'


def f(x):
    return f"{x:.2f}".rstrip("0").rstrip(".")


def cap_path(side, top, bottom):
    """Left cap: flat right edge, corners of radius top / bottom on the left. Right cap mirrors it."""
    pts = [
        ("M", [(W, 0)]),
        ("L", [(top, 0)]),
        ("C", [(top * K, 0), (0, top * K), (0, top)]),
        ("L", [(0, H - bottom)]),
        ("C", [(0, H - bottom * K), (bottom * K, H), (bottom, H)]),
        ("L", [(W, H)]),
    ]
    mirror = (lambda x: W - x) if side == "r" else (lambda x: x)
    return " ".join(cmd + " ".join(f"{f(mirror(x))},{f(y)}" for x, y in p) for cmd, p in pts) + " Z"


def vector(path, color, viewport=(W, H), size=("12dp", "24dp")):
    return (f'<vector android:width="{size[0]}" android:height="{size[1]}" '
            f'android:viewportWidth="{f(viewport[0])}" android:viewportHeight="{f(viewport[1])}">'
            f'<path android:name="p" android:fillColor="{color}" android:pathData="{path}"/></vector>')


def avd(path_from, path_to, color_from, color_to, viewport=(W, H), size=("12dp", "24dp")):
    morph = "" if path_from == path_to else (
        f'<objectAnimator android:propertyName="pathData" android:valueType="pathType" '
        f'android:duration="{MORPH_MS}" android:interpolator="{EMPHASIZED}" '
        f'android:valueFrom="{path_from}" android:valueTo="{path_to}"/>')
    color = (f'<objectAnimator android:propertyName="fillColor" android:valueType="colorType" '
             f'android:duration="{COLOR_MS}" android:interpolator="@android:interpolator/fast_out_slow_in" '
             f'android:valueFrom="{color_from}" android:valueTo="{color_to}"/>')
    return (f'<animated-vector><aapt:attr name="android:drawable">{vector(path_from, color_from, viewport, size)}</aapt:attr>'
            f'<target android:name="p"><aapt:attr name="android:animation"><set android:ordering="together">{morph}{color}</set>'
            f'</aapt:attr></target></animated-vector>')


def selector(off_path, on_path, **kw):
    """Chosen = disabled. Transitions both ways, so an interrupted change still lands softly."""
    return (HEADER +
            '<animated-selector xmlns:android="http://schemas.android.com/apk/res/android" '
            'xmlns:aapt="http://schemas.android.com/aapt" android:constantSize="true">\n'
            f'  <item android:id="@+id/w_seg_on" android:state_enabled="false"><aapt:attr name="android:drawable">{vector(on_path, "@color/w_on", **kw)}</aapt:attr></item>\n'
            f'  <item android:id="@+id/w_seg_off"><aapt:attr name="android:drawable">{vector(off_path, "@color/w_off", **kw)}</aapt:attr></item>\n'
            f'  <transition android:fromId="@id/w_seg_off" android:toId="@id/w_seg_on"><aapt:attr name="android:drawable">'
            f'{avd(off_path, on_path, "@color/w_off", "@color/w_on", **kw)}</aapt:attr></transition>\n'
            f'  <transition android:fromId="@id/w_seg_on" android:toId="@id/w_seg_off"><aapt:attr name="android:drawable">'
            f'{avd(on_path, off_path, "@color/w_on", "@color/w_off", **kw)}</aapt:attr></transition>\n'
            '</animated-selector>\n')


R = {"o": OUTER, "i": INNER}
CAPS = [(side, t, b) for side in "lr" for t, b in ("oo", "ii", "oi", "io")]


def drawables():
    out = {}
    for side, t, b in CAPS:
        out[f"w_seg_{side}_{t}{b}"] = selector(cap_path(side, R[t], R[b]), cap_path(side, OUTER, OUTER))
    rect = "M0,0 L10,0 L10,10 L0,10 Z"
    out["w_seg_mid"] = selector(rect, rect, viewport=(10, 10), size=("8dp", "8dp"))
    return out


# ---- layouts ---------------------------------------------------------------------------------

# Icons come from the app's Material Symbols font (docs/icon/symbols.py); the chosen mode shows
# the bolder cut, as the app's own buttons do.
MODES = [("anc", "w_icon_anc", "shortcut_anc"),
         ("amb", "w_icon_ambient", "shortcut_ambient"),
         ("off", "w_icon_off", "shortcut_off")]
ROW_CAPS = [("oo", "ii"), ("ii", "ii"), ("ii", "oo")]  # (left cap, right cap) per button
COLUMN_CAPS = [("oi", "oi"), ("ii", "ii"), ("io", "io")]


def tile(i, column, stacked, caps, indent):
    key, icon, text = MODES[i]
    lc, rc = caps[i]
    if column:
        size = 'android:layout_width="match_parent" android:layout_height="0dp" android:layout_weight="1"'
        gap = ' android:layout_marginTop="@dimen/w_gap"' if i else ""
    else:
        size = 'android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1"'
        gap = ' android:layout_marginStart="@dimen/w_gap"' if i else ""
    label_pad = 'android:paddingTop="4dp"' if stacked else 'android:paddingStart="8dp" tools:ignore="RtlSymmetry"'
    s = indent
    return f"""{s}<FrameLayout android:id="@+id/w_{key}"
{s}    {size}{gap}
{s}    android:clickable="true" android:focusable="true">
{s}    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
{s}        android:orientation="horizontal" android:duplicateParentState="true">
{s}        <ImageView android:layout_width="wrap_content" android:layout_height="match_parent"
{s}            android:adjustViewBounds="true" android:scaleType="fitXY" android:duplicateParentState="true"
{s}            android:importantForAccessibility="no" android:src="@drawable/w_seg_l_{lc}" />
{s}        <ImageView android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1"
{s}            android:scaleType="fitXY" android:duplicateParentState="true"
{s}            android:importantForAccessibility="no" android:src="@drawable/w_seg_mid" />
{s}        <ImageView android:layout_width="wrap_content" android:layout_height="match_parent"
{s}            android:adjustViewBounds="true" android:scaleType="fitXY" android:duplicateParentState="true"
{s}            android:importantForAccessibility="no" android:src="@drawable/w_seg_r_{rc}" />
{s}    </LinearLayout>
{s}    <LinearLayout android:id="@+id/w_{key}_content"
{s}        android:layout_width="match_parent" android:layout_height="match_parent"
{s}        android:gravity="center" android:orientation="{'vertical' if stacked else 'horizontal'}" android:paddingHorizontal="8dp"
{s}        android:duplicateParentState="true">
{s}        <FrameLayout android:id="@+id/w_{key}_icon"
{s}            android:layout_width="24dp" android:layout_height="24dp" android:duplicateParentState="true">
{s}            <ImageView android:layout_width="match_parent" android:layout_height="match_parent"
{s}                android:duplicateParentState="true" android:stateListAnimator="@animator/w_while_not_chosen"
{s}                android:importantForAccessibility="no" android:src="@drawable/{icon}" android:tint="@color/w_on" />
{s}            <ImageView android:layout_width="match_parent" android:layout_height="match_parent"
{s}                android:duplicateParentState="true" android:stateListAnimator="@animator/w_while_chosen" android:alpha="0"
{s}                android:importantForAccessibility="no" android:src="@drawable/{icon}_bold" android:tint="@color/w_on_text" />
{s}        </FrameLayout>
{s}        <FrameLayout android:id="@+id/w_{key}_label"
{s}            android:layout_width="wrap_content" android:layout_height="wrap_content"
{s}            {label_pad} android:duplicateParentState="true">
{s}            <TextView android:id="@+id/w_{key}_label_off" android:layout_width="wrap_content" android:layout_height="wrap_content"
{s}                android:fontFamily="google-sans-text-medium" android:textSize="14sp"
{s}                android:includeFontPadding="false" android:singleLine="true" android:ellipsize="none"
{s}                android:importantForAccessibility="no" android:duplicateParentState="true"
{s}                android:stateListAnimator="@animator/w_while_not_chosen" android:textColor="@color/w_off_text"
{s}                android:text="@string/{text}" />
{s}            <TextView android:id="@+id/w_{key}_label_on" android:layout_width="wrap_content" android:layout_height="wrap_content"
{s}                android:fontFamily="google-sans-text-medium" android:textSize="14sp"
{s}                android:includeFontPadding="false" android:singleLine="true" android:ellipsize="none"
{s}                android:importantForAccessibility="no" android:duplicateParentState="true"
{s}                android:stateListAnimator="@animator/w_while_chosen" android:alpha="0" android:textColor="@color/w_on_text"
{s}                android:text="@string/{text}" />
{s}        </FrameLayout>
{s}    </LinearLayout>
{s}</FrameLayout>
"""


def tiles(column, stacked, indent):
    caps = COLUMN_CAPS if column else ROW_CAPS
    return "".join(tile(i, column, stacked, caps, indent) for i in range(3))


def modes_layout(comment, column, stacked):
    return (HEADER + f"""<!-- {comment} The chosen mode is disabled; its segments morph into a pill. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android" xmlns:tools="http://schemas.android.com/tools"
    tools:ignore="UselessParent" android:id="@android:id/background"
    android:layout_width="match_parent" android:layout_height="match_parent"
    android:background="@drawable/w_bg" android:padding="@dimen/w_pad">
<LinearLayout android:id="@+id/w_group"
    android:layout_width="match_parent" android:layout_height="match_parent" android:layout_gravity="center"
    android:orientation="{'vertical' if column else 'horizontal'}" android:baselineAligned="false">
""" + tiles(column, stacked, "    ") + "</LinearLayout>\n</FrameLayout>\n")


def main():
    for name, text in drawables().items():
        (RES / "drawable" / f"{name}.xml").write_text(text)
    layouts = RES / "layout"
    (layouts / "widget_modes.xml").write_text(modes_layout("Row of three; icon above label. Default and launcher preview.", False, True))
    (layouts / "widget_modes_inline.xml").write_text(modes_layout("Row of three; icon beside label, for wide and short widgets.", False, False))
    (layouts / "widget_modes_column.xml").write_text(modes_layout("Column of three, for narrow and tall widgets.", True, False))
    # The dashboard keeps its own header and batteries; only the mode row between the markers is generated.
    dash = layouts / "widget_dashboard.xml"
    s = dash.read_text()
    start, end = "<!-- modes:start -->\n", "        <!-- modes:end -->"
    a, b = s.index(start) + len(start), s.index(end)
    dash.write_text(s[:a] + tiles(False, False, "        ") + s[b:])


if __name__ == "__main__":
    main()
