"""Faithful WF-1000XM5 pictures for the app, drawn as vectors from the real product.

    pip install numpy pillow potracer
    python3 docs/icon/product_glyphs.py

The case: its outline is the profile measured row by row from the product photo (casepath.py,
which matches Sony's 64.6 x 40.0 x 26.5 mm case seen from the front and a little above, h/w
0.643). The lid meets the body at 43 % of the height, where the photo's seam runs; the status
light sits just below it in the middle. The earbud: traced from the product render as
bud_glyph.py does (silhouette, the seam arc between shell and ear tip, the round grille).

Writes, in the product's platinum silver:
  art_case.xml, art_bud_left.xml, art_bud_right.xml   colour, for Home's rings and Device info
  ic_case_mark.xml                                      one tint, for widgets and notifications
(the earbud's one-tint glyph stays w_glyph_bud_*, from bud_glyph.py).
"""
import math
import sys
from pathlib import Path

import numpy as np
import potrace
from PIL import Image, ImageDraw, ImageFilter

sys.path.insert(0, str(Path(__file__).parent))
import bud_glyph  # noqa: E402
import casepath  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "app/src/main/res/drawable"
HEAD = "<!-- Generated by docs/icon/product_glyphs.py; edit the script, not this file. -->"

SEAM = 0.432       # lid / body, share of the case height (measured on the photo)
LED = (0.5, 0.51)  # the status light, share of width and height
# Platinum silver, lit from the top left.
LID = ("#FFF4F5F7", "#FFD8DCE2")
BODY = ("#FFE6E8EC", "#FFB3B9C2")
SEAM_LINE = "#FF8B929C"
SHELL = ("#FFF6F7F9", "#FFDCE0E5", "#FFB2B8C1")
TIP = ("#FF9AA0A8", "#FF5E636B")
GRILLE = ("#FFE3B47E", "#FF9C6A3A")


def f(v):
    return f"{v:.2f}".rstrip("0").rstrip(".")


def grad(x0, y0, x1, y1, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="linear" android:startX="{f(x0)}" '
            f'android:startY="{f(y0)}" android:endX="{f(x1)}" android:endY="{f(y1)}">{items}</gradient></aapt:attr>')


def radial(cx, cy, r, stops):
    items = "".join(f'<item android:offset="{o}" android:color="{c}"/>' for o, c in stops)
    return (f'<aapt:attr name="android:fillColor"><gradient android:type="radial" android:centerX="{f(cx)}" '
            f'android:centerY="{f(cy)}" android:gradientRadius="{f(r)}">{items}</gradient></aapt:attr>')


def vector(w, h, body, comment):
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{HEAD}\n<!-- {comment} -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
            '    xmlns:tools="http://schemas.android.com/tools" tools:ignore="VectorPath"\n'
            f'    android:width="{f(w)}dp" android:height="{f(h)}dp" android:viewportWidth="{f(w)}" android:viewportHeight="{f(h)}">\n'
            f'{body}</vector>\n')


# ---- the case -----------------------------------------------------------------------------------

def case_files():
    W = 64.0
    H = W * casepath.ASPECT
    d = casepath.path_d(casepath.bezier(casepath.outline(W, W / 2, H / 2)))
    seam = H * SEAM
    lx, ly = W * LED[0], H * LED[1]
    colour = (
        f'    <path android:pathData="{d}">{grad(0, seam, 0, H, [(0, BODY[0]), (1, BODY[1])])}</path>\n'
        f'    <group><clip-path android:pathData="M0,0 H{f(W)} V{f(seam)} H0 Z"/>\n'
        f'        <path android:pathData="{d}">{grad(0, 0, 0, seam, [(0, LID[0]), (1, LID[1])])}</path></group>\n'
        # the seam: a fine dark line across the case, kept inside its outline
        f'    <group><clip-path android:pathData="{d}"/>\n'
        f'        <path android:fillColor="{SEAM_LINE}" android:pathData="M0,{f(seam - 0.35)} H{f(W)} V{f(seam + 0.35)} H0 Z"/></group>\n'
        f'    <path android:fillColor="#FF4C5158" android:pathData="M{f(lx - 0.9)},{f(ly)} a0.9,0.9 0 1,0 1.8,0 a0.9,0.9 0 1,0 -1.8,0 Z"/>\n'
    )
    (OUT / "art_case.xml").write_text(vector(W, H, colour,
        "The WF-1000XM5 case, front, a little from above: Home's case ring and Device info."))
    # One tint: the case with the seam cut through it, at the 24 dp of a small icon.
    k = 22.0 / W
    d24 = casepath.path_d(casepath.bezier(casepath.outline(22.0, 12.0, 12.0)))
    top = 12.0 - 22.0 * casepath.ASPECT / 2
    s24 = top + 22.0 * casepath.ASPECT * SEAM
    mark = (
        f'    <group><clip-path android:pathData="M0,0 H24 V{f(s24 - 0.5)} H0 Z"/>\n'
        f'        <path android:fillColor="#FF000000" android:pathData="{d24}"/></group>\n'
        f'    <group><clip-path android:pathData="M0,{f(s24 + 0.5)} H24 V24 H0 Z"/>\n'
        f'        <path android:fillColor="#FF000000" android:pathData="{d24}"/></group>\n'
    )
    (OUT / "ic_case_mark.xml").write_text(vector(24, 24, mark,
        "The WF-1000XM5 case as a one-tint mark (widgets, notifications): its true outline, the seam cut through.").replace(
        'android:width="24dp" android:height="24dp"', 'android:width="24dp" android:height="24dp"'))
    _ = k


# ---- the earbud ------------------------------------------------------------------------------------

def bud_masks():
    """The render's silhouette split into shell and ear tip along the seam arc, and the grille."""
    S = bud_glyph.S
    src = Image.open(bud_glyph.RENDER).convert("RGBA")
    size = src.size[0] * S
    src = src.resize((size, size), Image.LANCZOS)
    r, g, b, a = (np.asarray(c, dtype=float) for c in src.split())
    shape = a > 128
    gold = (r > g + 10) & (g > b + 25) & shape & (r > 90)
    ys, xs = np.nonzero(gold)
    grille = (xs.mean() / S, ys.mean() / S, math.sqrt(gold.sum() / math.pi) / S)
    yy, xx = np.mgrid[0:size, 0:size] / S
    dist = np.hypot(xx - bud_glyph.SEAM_CENTER[0], yy - bud_glyph.SEAM_CENTER[1])
    shell = shape & (dist <= bud_glyph.SEAM_RADIUS)
    tip = shape & (dist >= bud_glyph.SEAM_RADIUS + 1.2)

    def smooth(m):
        img = Image.fromarray((m * 255).astype("uint8")).filter(ImageFilter.GaussianBlur(2))
        return np.asarray(img.point(lambda v: 255 if v > 127 else 0)) > 127
    return smooth(shape), smooth(shell), smooth(tip), grille, S


def traced(m, scale, ox, oy):
    h, w = m.shape
    parts = []
    for c in potrace.Bitmap(m).trace(turdsize=200, alphamax=1.1, opticurve=True, opttolerance=0.8):
        xs = [c.start_point.x] + [s.end_point.x for s in c.segments]
        if min(xs) < 1 and max(xs) > w - 1:
            continue
        p = lambda q: f"{q.x * scale + ox:.2f},{q.y * scale + oy:.2f}"
        seg = [f"M{p(c.start_point)}"]
        for s in c.segments:
            seg.append(f"L{p(s.c)} L{p(s.end_point)}" if s.is_corner else f"C{p(s.c1)} {p(s.c2)} {p(s.end_point)}")
        parts.append(" ".join(seg) + "Z")
    return " ".join(parts)


def bud_files():
    shape, shell, tip, (gx, gy, gr), S = bud_masks()
    ys, xs = np.nonzero(shape)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    scale = 22.0 / max(x1 - x0, y1 - y0)
    ox = 1 + (22 - (x1 - x0) * scale) / 2 - x0 * scale
    oy = 1 + (22 - (y1 - y0) * scale) / 2 - y0 * scale
    shell_d = traced(shell, scale, ox, oy)
    tip_d = traced(tip, scale, ox, oy)
    cx, cy, cr = gx * S * scale + ox, gy * S * scale + oy, gr * S * scale
    body = (
        f'    <path android:pathData="{tip_d}">{radial(cx - 6, cy + 1, 9, [(0, TIP[0]), (1, TIP[1])])}</path>\n'
        f'    <path android:pathData="{shell_d}">{radial(9, 6, 17, [(0, SHELL[0]), (0.55, SHELL[1]), (1, SHELL[2])])}</path>\n'
        f'    <path android:pathData="M{f(cx - cr)},{f(cy)} a{f(cr)},{f(cr)} 0 1,0 {f(2 * cr)},0 a{f(cr)},{f(cr)} 0 1,0 {f(-2 * cr)},0 Z">'
        f'{grad(cx - cr, cy - cr, cx + cr, cy + cr, [(0, GRILLE[0]), (1, GRILLE[1])])}</path>\n'
        f'    <path android:fillColor="#40000000" android:pathData="M{f(cx - cr * 0.55)},{f(cy)} a{f(cr * 0.55)},{f(cr * 0.55)} 0 1,0 {f(cr * 1.1)},0 a{f(cr * 0.55)},{f(cr * 0.55)} 0 1,0 {f(-cr * 1.1)},0 Z"/>\n'
    )
    for name, mirror in (("art_bud_left", False), ("art_bud_right", True)):
        content = f'    <group android:pivotX="12" android:scaleX="-1">\n{body}    </group>\n' if mirror else body
        (OUT / f"{name}.xml").write_text(vector(24, 24, content,
            "A WF-1000XM5 earbud in its colours (shell, ear tip, copper grille): Home's rings and Device info."))


if __name__ == "__main__":
    case_files()
    bud_files()
