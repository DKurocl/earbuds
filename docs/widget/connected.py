"""Generates the mode widget as Material 3 Expressive's connected button group.

    python3 docs/widget/connected.py

Three tonal segments joined by 2 dp gaps: the group's outer corners are fully round, the inner
ones small. The chosen mode's segment morphs into a full pill (all four corners round) while its
color turns from the tonal container to primary, the way a connected button group shows its
selection; the old one morphs back. Icon and label exist twice (rest and chosen colors, regular
and bold icon) and cross-fade in step through res/animator/w_while_*.xml.

How: a widget can't animate a shape's corners, so each segment is three images in a row, a
left cap, a stretching middle and a right cap. A cap is half as wide as the segment is tall
(adjustViewBounds keeps its 1:2 ratio), so its vector scales uniformly and its corners stay true.
Each image is an animated-selector on the segment's enabled state: the chosen mode is disabled,
so only a real change animates and the launcher can re-apply the same update without replaying.
"""
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res"
K = 0.44772
W, H = 50.0, 100.0
ROUND, INNER = 50.0, 16.0   # full round; the inner corner, 8 dp at a 48 dp tall group
MORPH_MS, COLOR_MS = 350, 250
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by docs/widget/connected.py; edit the script, not this file. -->\n'


def f(x):
    return f"{x:.2f}".rstrip("0").rstrip(".")


def cap(side, r):
    pts = [("M", [(W, 0)]), ("L", [(r, 0)]), ("C", [(r * K, 0), (0, r * K), (0, r)]),
           ("L", [(0, H - r)]), ("C", [(0, H - r * K), (r * K, H), (r, H)]), ("L", [(W, H)])]
    mx = (lambda x: W - x) if side == "r" else (lambda x: x)
    return " ".join(c + " ".join(f"{f(mx(x))},{f(y)}" for x, y in p) for c, p in pts) + " Z"


def vector(path, color, vp, size):
    return (f'<vector android:width="{size[0]}" android:height="{size[1]}" android:viewportWidth="{f(vp[0])}" '
            f'android:viewportHeight="{f(vp[1])}"><path android:name="p" android:fillColor="{color}" android:pathData="{path}"/></vector>')


def avd(p0, p1, c0, c1, vp, size):
    morph = "" if p0 == p1 else (
        f'<objectAnimator android:propertyName="pathData" android:valueType="pathType" android:duration="{MORPH_MS}" '
        f'android:interpolator="@interpolator/w_emphasized" android:valueFrom="{p0}" android:valueTo="{p1}"/>')
    tint = (f'<objectAnimator android:propertyName="fillColor" android:valueType="colorType" android:duration="{COLOR_MS}" '
            f'android:interpolator="@android:interpolator/fast_out_slow_in" android:valueFrom="{c0}" android:valueTo="{c1}"/>')
    return (f'<animated-vector><aapt:attr name="android:drawable">{vector(p0, c0, vp, size)}</aapt:attr>'
            f'<target android:name="p"><aapt:attr name="android:animation"><set android:ordering="together">{morph}{tint}</set>'
            f'</aapt:attr></target></animated-vector>')


def selector(off, on, vp=(W, H), size=("12dp", "24dp")):
    c0, c1 = "@color/w_seg", "@color/w_bar_on"
    return (HEADER + '<animated-selector xmlns:android="http://schemas.android.com/apk/res/android" '
            'xmlns:aapt="http://schemas.android.com/aapt" android:constantSize="true">\n'
            f'  <item android:id="@+id/w_cs_on" android:state_enabled="false"><aapt:attr name="android:drawable">{vector(on, c1, vp, size)}</aapt:attr></item>\n'
            f'  <item android:id="@+id/w_cs_off"><aapt:attr name="android:drawable">{vector(off, c0, vp, size)}</aapt:attr></item>\n'
            f'  <transition android:fromId="@id/w_cs_off" android:toId="@id/w_cs_on"><aapt:attr name="android:drawable">{avd(off, on, c0, c1, vp, size)}</aapt:attr></transition>\n'
            f'  <transition android:fromId="@id/w_cs_on" android:toId="@id/w_cs_off"><aapt:attr name="android:drawable">{avd(on, off, c1, c0, vp, size)}</aapt:attr></transition>\n'
            '</animated-selector>\n')


def drawables():
    rect = "M0,0 L10,0 L10,10 L0,10 Z"
    return {
        "w_cs_outer_l": selector(cap("l", ROUND), cap("l", ROUND)),
        "w_cs_outer_r": selector(cap("r", ROUND), cap("r", ROUND)),
        "w_cs_inner_l": selector(cap("l", INNER), cap("l", ROUND)),
        "w_cs_inner_r": selector(cap("r", INNER), cap("r", ROUND)),
        "w_cs_mid": selector(rect, rect, vp=(10, 10), size=("8dp", "8dp")),
    }


MODES = [("anc", "w_icon_anc", "shortcut_anc"), ("amb", "w_icon_ambient", "shortcut_ambient"), ("off", "w_icon_off", "shortcut_off")]


def segment(i, stacked):
    key, icon, text = MODES[i]
    left = "w_cs_outer_l" if i == 0 else "w_cs_inner_l"
    right = "w_cs_outer_r" if i == 2 else "w_cs_inner_r"
    gap = ' android:layout_marginStart="2dp"' if i else ""
    orient = "vertical" if stacked else "horizontal"
    label_gap = 'android:layout_marginTop="4dp"' if stacked else 'android:layout_marginStart="6dp"'
    def img(src, w):
        extra = 'android:adjustViewBounds="true"' if w == "wrap_content" else 'android:layout_weight="1"'
        return (f'                <ImageView android:layout_width="{w}" android:layout_height="match_parent" {extra}\n'
                f'                    android:scaleType="fitXY" android:duplicateParentState="true"\n'
                f'                    android:importantForAccessibility="no" android:src="@drawable/{src}" />\n')
    def label(suffix, color, anim, alpha):
        return (f'                    <TextView android:id="@+id/w_{key}_label_{suffix}" android:layout_width="wrap_content" android:layout_height="wrap_content"\n'
                f'                        android:fontFamily="google-sans-text-medium" android:textSize="14sp" android:includeFontPadding="false"\n'
                f'                        android:singleLine="true" android:importantForAccessibility="no" android:duplicateParentState="true"\n'
                f'                        android:stateListAnimator="@animator/{anim}"{alpha} android:textColor="@color/{color}" android:text="@string/{text}" />\n')
    return f"""        <FrameLayout android:id="@+id/w_{key}"
            android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1"{gap}
            android:clickable="true" android:focusable="true">
            <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent"
                android:orientation="horizontal" android:duplicateParentState="true">
{img(left, "wrap_content")}{img("w_cs_mid", "0dp")}{img(right, "wrap_content")}            </LinearLayout>
            <LinearLayout android:id="@+id/w_{key}_content" android:layout_width="wrap_content" android:layout_height="wrap_content"
                android:layout_gravity="center" android:gravity="center" android:orientation="{orient}"
                android:duplicateParentState="true">
                <FrameLayout android:id="@+id/w_{key}_icon" android:layout_width="24dp" android:layout_height="24dp"
                    android:duplicateParentState="true">
                    <ImageView android:layout_width="match_parent" android:layout_height="match_parent"
                        android:duplicateParentState="true" android:stateListAnimator="@animator/w_while_not_chosen"
                        android:importantForAccessibility="no" android:src="@drawable/{icon}" android:tint="@color/w_bar_text" />
                    <ImageView android:layout_width="match_parent" android:layout_height="match_parent"
                        android:duplicateParentState="true" android:stateListAnimator="@animator/w_while_chosen" android:alpha="0"
                        android:importantForAccessibility="no" android:src="@drawable/{icon}_bold" android:tint="@color/w_bar_on_text" />
                </FrameLayout>
                <FrameLayout android:id="@+id/w_{key}_label" android:layout_width="wrap_content" android:layout_height="wrap_content"
                    {label_gap} android:duplicateParentState="true">
{label("off", "w_bar_text", "w_while_not_chosen", "")}{label("on", "w_bar_on_text", "w_while_chosen", ' android:alpha="0"')}                </FrameLayout>
            </LinearLayout>
        </FrameLayout>
"""


def layout(stacked):
    kind = "Tall: label under the icon." if stacked else "Short: label beside the icon."
    return (HEADER + f"""<!-- Connected button group widget. {kind} The side edges open the app. -->
<FrameLayout xmlns:android="http://schemas.android.com/apk/res/android" xmlns:tools="http://schemas.android.com/tools"
    tools:ignore="UselessParent" android:id="@android:id/background"
    android:layout_width="match_parent" android:layout_height="match_parent"
    android:background="@drawable/w_bar_bg" android:paddingHorizontal="20dp" android:paddingVertical="6dp">
    <LinearLayout android:id="@+id/w_group"
        android:layout_width="match_parent" android:layout_height="48dp" android:layout_gravity="center"
        android:orientation="horizontal" android:baselineAligned="false">
""" + "".join(segment(i, stacked) for i in range(3)) + """    </LinearLayout>
</FrameLayout>
""")


def player_slot_mode(key, icon, text):
    return f"""        <FrameLayout android:id="@+id/w_{key}"
            android:layout_width="0dp" android:layout_height="match_parent" android:layout_weight="1"
            android:clickable="true" android:focusable="true">
            <ImageView android:layout_width="match_parent" android:layout_height="match_parent"
                android:layout_marginHorizontal="2dp" android:layout_marginVertical="5dp"
                android:src="@drawable/w_player_pill"
                android:scaleType="fitXY" android:duplicateParentState="true"
                android:stateListAnimator="@animator/w_while_chosen" android:alpha="0"
                android:importantForAccessibility="no" />
            <ImageView android:layout_width="24dp" android:layout_height="24dp"
                android:layout_gravity="center" android:src="@drawable/{icon}" android:tint="@color/w_bar_text"
                android:duplicateParentState="true" android:stateListAnimator="@animator/w_while_not_chosen"
                android:importantForAccessibility="no" />
            <LinearLayout android:layout_width="match_parent" android:layout_height="wrap_content"
                android:layout_gravity="center" android:gravity="center" android:orientation="vertical"
                android:duplicateParentState="true" android:stateListAnimator="@animator/w_while_chosen"
                android:alpha="0" android:importantForAccessibility="noHideDescendants">
                <ImageView android:layout_width="22dp" android:layout_height="22dp"
                    android:src="@drawable/{icon}_bold" android:tint="@color/w_bar_on_text" />
                <TextView android:id="@+id/w_{key}_label_on" android:layout_width="match_parent"
                    android:layout_height="wrap_content" android:layout_marginTop="2dp"
                    android:paddingHorizontal="5dp" android:gravity="center" android:singleLine="true"
                    android:ellipsize="end" android:includeFontPadding="false" android:textSize="12sp"
                    android:fontFamily="google-sans-text-medium" android:textColor="@color/w_bar_on_text"
                    android:text="@string/{text}" />
            </LinearLayout>
        </FrameLayout>
"""


def player_slot_layout():
    return HEADER + """<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"
    android:id="@android:id/background" android:layout_width="match_parent" android:layout_height="match_parent"
    android:orientation="horizontal" android:gravity="center_vertical" android:baselineAligned="false"
    android:background="@drawable/w_bar_bg">
    <FrameLayout android:id="@+id/w_open_left" android:layout_width="48dp" android:layout_height="match_parent" />
    <LinearLayout android:layout_width="0dp" android:layout_height="58dp" android:layout_weight="1"
        android:orientation="horizontal" android:baselineAligned="false">
""" + "".join(player_slot_mode(*mode) for mode in MODES) + """    </LinearLayout>
    <FrameLayout android:id="@+id/w_open_right" android:layout_width="48dp" android:layout_height="match_parent"
        android:importantForAccessibility="no" />
</LinearLayout>
"""


def main():
    for name, xml in drawables().items():
        (RES / f"drawable/{name}.xml").write_text(xml)
    (RES / "layout/widget_group.xml").write_text(layout(False))
    (RES / "layout/widget_group_tall.xml").write_text(layout(True))
    (RES / "layout/widget_player_slot.xml").write_text(player_slot_layout())


if __name__ == "__main__":
    main()
