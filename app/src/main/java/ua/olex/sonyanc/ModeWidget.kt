package ua.olex.sonyanc

import android.app.PendingIntent
import android.appwidget.AppWidgetManager
import android.appwidget.AppWidgetProvider
import android.content.ComponentName
import android.content.Context
import android.content.Intent
import android.os.Bundle
import android.util.SizeF
import android.util.TypedValue
import android.view.View
import android.os.Handler
import android.os.Looper
import android.widget.RemoteViews
import android.widget.Toast
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch
import kotlinx.coroutines.withTimeoutOrNull
import java.util.concurrent.atomic.AtomicLong

/**
 * Three controls only: ANC, Ambient, Off, as Material 3 Expressive's connected button group: the
 * chosen segment morphs into a primary pill; the wide side edges open the app. A tap on a mode reconnects on
 * demand and sets it.
 * No persistent service or notification. Large slots get the dashboard.
 */
class ModeWidget : AppWidgetProvider() {
    override fun onUpdate(ctx: Context, mgr: AppWidgetManager, ids: IntArray) = render(ctx,mgr,ids)
    override fun onAppWidgetOptionsChanged(ctx:Context,mgr:AppWidgetManager,id:Int,options:Bundle) {
        super.onAppWidgetOptionsChanged(ctx,mgr,id,options)
        render(ctx,mgr,intArrayOf(id))
    }

    override fun onReceive(ctx: Context, intent: Intent) {
        super.onReceive(ctx,intent)
        if(intent.action!=ACTION_SET) return
        val mode=intent.getStringExtra(EXTRA_MODE)?.let {runCatching{SonyProtocol.Mode.valueOf(it)}.getOrNull()} ?: return
        Headphones.init(ctx)
        AmbientTimer.cancel(ctx) // a manual choice wins over "Ambient for a moment"
        val pending=goAsync()
        val generation=latestTap.incrementAndGet()
        // The highlight moves (animated) on the tap itself; only the command waits for a burst to settle.
        busyMode=mode
        refreshAll(ctx)
        CoroutineScope(Dispatchers.IO).launch {
            Headphones.hold(foreground=false)
            try {
                delay(70)
                if(latestTap.get()!=generation) return@launch
                val base=Headphones.state.value.shownNc ?: SonyProtocol.NcState(mode)
                val receipt=Headphones.request(base.copy(mode=mode))
                var delivered = false
                withTimeoutOrNull(8500) {
                    delivered = receipt.await()
                    if (delivered && latestTap.get() == generation) {
                        if (Prefs.haptics(ctx)) Haptics.confirm(ctx, mode)
                        // Keep the short lease until the reported mode can replace the animation.
                        ModeControl.awaitModeIdle()
                    }
                }
                if (!delivered && latestTap.get() == generation) {
                    if (Prefs.haptics(ctx)) Haptics.reject(ctx)
                    showFailure(ctx)
                }
            } catch(e:Exception) {
                if(latestTap.get()==generation) showFailure(ctx)
            } finally {
                if(latestTap.get()==generation) {busyMode=null;refreshAll(ctx)}
                Headphones.release(foreground=false)
                pending.finish()
            }
        }
    }

    companion object {
        private const val ACTION_SET="ua.olex.sonyanc.SET_MODE"
        private const val EXTRA_MODE="mode"
        private val latestTap=AtomicLong()
        @Volatile private var busyMode:SonyProtocol.Mode?=null
        /** A mode button (generated by docs/widget/segments.py): morphing segments behind [content]. */
        private data class Tile(val mode:SonyProtocol.Mode,val id:Int,val content:Int,val icon:Int,val label:Int,val texts:List<Int>)
        private val tiles=listOf(
            Tile(SonyProtocol.Mode.ANC,R.id.w_anc,R.id.w_anc_content,R.id.w_anc_icon,R.id.w_anc_label,
                listOf(R.id.w_anc_label_off,R.id.w_anc_label_on)),
            Tile(SonyProtocol.Mode.AMBIENT,R.id.w_amb,R.id.w_amb_content,R.id.w_amb_icon,R.id.w_amb_label,
                listOf(R.id.w_amb_label_off,R.id.w_amb_label_on)),
            Tile(SonyProtocol.Mode.OFF,R.id.w_off,R.id.w_off_content,R.id.w_off_icon,R.id.w_off_label,
                listOf(R.id.w_off_label_off,R.id.w_off_label_on)),
        )
        /** Used before the launcher reports sizes: the system picks the best fit. */
        private val FALLBACK=listOf(SizeF(180f,64f),SizeF(300f,64f),SizeF(322f,105f),SizeF(340f,100f),SizeF(420f,100f),SizeF(180f,220f),SizeF(420f,220f))

        private fun showFailure(ctx:Context) {
            val text=if(Prefs.linked(ctx)==false) "Earbuds aren't connected to this phone." else "Couldn't reach the earbuds. Tap a mode to retry."
            Handler(Looper.getMainLooper()).post {Toast.makeText(ctx,text,Toast.LENGTH_SHORT).show()}
        }

        fun refreshAll(ctx:Context) {
            val mgr=AppWidgetManager.getInstance(ctx)
            val ids=mgr.getAppWidgetIds(ComponentName(ctx,ModeWidget::class.java))
            if(ids.isNotEmpty()) render(ctx,mgr,ids)
        }

        private fun render(ctx:Context,mgr:AppWidgetManager,ids:IntArray) {
            val current=Prefs.lastNc(ctx)?.mode
            val linked=Prefs.linked(ctx)
            for(id in ids) {
                val sizes=Widgets.sizes(mgr.getAppWidgetOptions(id),FALLBACK)
                val category = mgr.getAppWidgetOptions(id).getInt(AppWidgetManager.OPTION_APPWIDGET_HOST_CATEGORY)
                val showDashboard = category == android.appwidget.AppWidgetProviderInfo.WIDGET_CATEGORY_KEYGUARD
                mgr.updateAppWidget(id,Widgets.forSizes(sizes){
                    viewsFor(ctx,it.width,it.height,current,busyMode,linked=linked,showDashboard=showDashboard)
                })
            }
        }

        /** The exact views for one widget size. The debug gallery and the picker preview use this too. */
        internal fun viewsFor(ctx:Context,width:Float,height:Float,current:SonyProtocol.Mode?,pending:SonyProtocol.Mode?=null,
                              interactive:Boolean=true,linked:Boolean?=Prefs.linked(ctx),
                              battery:Pair<SonyProtocol.Battery,Long>?=Prefs.lastBattery(ctx), showDashboard:Boolean=true):RemoteViews {
        if (showDashboard) WidgetLayout.dashboard(width,height,Widgets.lineHeight(ctx,16f,"google-sans-text-medium"),
            Widgets.lineHeight(ctx,14f,"google-sans-text-medium"),Widgets.lineHeight(ctx,13f),
            SonyProtocol.Mode.entries.maxOf{Widgets.textWidth(ctx,it.short,14f)})?.let {
            return dashboard(ctx,it,current,pending,interactive,linked,battery)
        }
            if (width in 310f..334f && height in 98f..112f) {
                return playerSlot(ctx, current, pending, linked == false, interactive)
            }
            return switch(ctx,width,height,current,pending,linked==false,interactive)
        }

        /** A mode's segment and the parts the widget sizes: icon box and label (both colors live inside). */
        private data class Segment(val mode:SonyProtocol.Mode,val id:Int,val icon:Int,val label:Int,val texts:List<Int>)
        private val segments=listOf(
            Segment(SonyProtocol.Mode.ANC,R.id.w_anc,R.id.w_anc_icon,R.id.w_anc_label,listOf(R.id.w_anc_label_off,R.id.w_anc_label_on)),
            Segment(SonyProtocol.Mode.AMBIENT,R.id.w_amb,R.id.w_amb_icon,R.id.w_amb_label,listOf(R.id.w_amb_label_off,R.id.w_amb_label_on)),
            Segment(SonyProtocol.Mode.OFF,R.id.w_off,R.id.w_off_icon,R.id.w_off_label,listOf(R.id.w_off_label_off,R.id.w_off_label_on)),
        )

        /** The single-row home-screen slot beside the owner's media widget. */
        private fun playerSlot(ctx: Context, current: SonyProtocol.Mode?, pending: SonyProtocol.Mode?,
                               away: Boolean, interactive: Boolean): RemoteViews {
            val views = RemoteViews(ctx.packageName, R.layout.widget_player_slot)
            if (interactive) {
                val open = openApp(ctx)
                views.setOnClickPendingIntent(R.id.w_open_left, open)
                views.setOnClickPendingIntent(R.id.w_open_right, open)
                views.setContentDescription(R.id.w_open_left, ctx.getString(R.string.widget_open_app))
            }
            for (segment in segments) bindMode(ctx, views, segment, current, pending, away, interactive)
            return views
        }

        private val intentFlags = PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE

        private fun openApp(ctx: Context): PendingIntent {
            val intent = Intent(ctx, MainActivity::class.java)
                .setFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
            return PendingIntent.getActivity(ctx, 101, intent, intentFlags)
        }

        private fun bindMode(ctx: Context, views: RemoteViews, segment: Segment, current: SonyProtocol.Mode?,
                             pending: SonyProtocol.Mode?, away: Boolean, interactive: Boolean) {
            val mode = segment.mode
            val chosen = mode == (pending ?: current)
            val status = when {
                mode == pending -> ", applying"
                chosen -> ", selected"
                else -> ""
            }
            views.setBoolean(segment.id, "setEnabled", !chosen)
            views.setContentDescription(segment.id, mode.label + status + if (away) ", earbuds not connected" else "")
            if (!interactive) return
            val action = if (Prefs.deviceAddress(ctx) == null || !Headphones.hasPermission(ctx)) {
                val setup = Intent(ctx, MainActivity::class.java).putExtra("hush.mode", mode.name)
                PendingIntent.getActivity(ctx, mode.ordinal, setup, intentFlags)
            } else {
                val set = Intent(ctx, ModeWidget::class.java).setAction(ACTION_SET).putExtra(EXTRA_MODE, mode.name)
                PendingIntent.getBroadcast(ctx, mode.ordinal, set, intentFlags)
            }
            views.setOnClickPendingIntent(segment.id, action)
        }

        /**
         * Material 3 Expressive's connected button group (docs/widget/connected.py): three tonal
         * segments; the chosen one (the pending choice wins) is disabled, which morphs its corners
         * into a full pill and its color into primary, while the old one morphs back. A segment
         * sets its mode; the side edges open the app. The group fills the slot's height up to
         * where a segment would be taller than wide; tall groups put the label under the icon.
         */
        private fun switch(ctx:Context,width:Float,height:Float,current:SonyProtocol.Mode?,pending:SonyProtocol.Mode?,
                           away:Boolean,interactive:Boolean):RemoteViews {
            val slot=(width-40f-4f)/3f
            // Tuned for the owner's slot (322 x 105 dp, beside the media player): a 60 dp group with
            // the label under the icon, about 22 dp of bar above and below as the player has, and
            // segments half again as wide as tall, so the chosen one is a stadium like the player's
            // play button, never a circle.
            val bar=minOf(60f,height-24f,slot/1.5f).coerceAtLeast(32f)
            val stacked=bar>=56f
            val v=RemoteViews(ctx.packageName,if(stacked) R.layout.widget_group_tall else R.layout.widget_group)
            val iconSize=24f
            val widest=SonyProtocol.Mode.entries.maxOf{Widgets.textWidth(ctx,it.short,14f)}
            val labels=if(stacked) slot>=widest+16f else slot>=iconSize+6f+widest+20f
            v.setViewLayoutHeight(R.id.w_group,bar,TypedValue.COMPLEX_UNIT_DIP)
            if (interactive) v.setOnClickPendingIntent(android.R.id.background, openApp(ctx))
            for (seg in segments) {
                v.setViewLayoutWidth(seg.icon, iconSize, TypedValue.COMPLEX_UNIT_DIP)
                v.setViewLayoutHeight(seg.icon, iconSize, TypedValue.COMPLEX_UNIT_DIP)
                for (text in seg.texts) v.setTextViewText(text, seg.mode.short)
                v.setViewVisibility(seg.label, if (labels) View.VISIBLE else View.GONE)
                bindMode(ctx, v, seg, current, pending, away, interactive)
            }
            return v
        }

        /**
         * Binds the three buttons. The chosen one (the pending choice wins over the last confirmed
         * one) is disabled: its segments morph into a pill and change color. Only a real state
         * change animates, so the launcher can re-apply the same update without replaying it, and
         * a fresh inflation (reboot, resize) starts in place. Unconfirmed choices move back the same way.
         */
        private fun bindTiles(ctx:Context,v:RemoteViews,current:SonyProtocol.Mode?,pending:SonyProtocol.Mode?,
                              away:Boolean,labels:Boolean,icon:Float,interactive:Boolean) {
            // Anywhere that is not a mode (the padding, the gaps between the modes, the header and
            // rings of the dashboard) opens the app, as Google's own widgets do; a mode sets it.
            if(interactive) {
                val open=Intent(ctx,MainActivity::class.java).setFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
                val openApp=PendingIntent.getActivity(ctx,101,open,PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE)
                v.setOnClickPendingIntent(android.R.id.background,openApp)
                v.setOnClickPendingIntent(R.id.w_group,openApp)
            }
            val chosen=pending ?: current
            for(tile in tiles) {
                val mode=tile.mode
                val on=mode==chosen
                val applying=mode==pending
                v.setBoolean(tile.id,"setEnabled",!on)
                v.setViewLayoutWidth(tile.icon,icon,TypedValue.COMPLEX_UNIT_DIP)
                v.setViewLayoutHeight(tile.icon,icon,TypedValue.COMPLEX_UNIT_DIP)
                for(text in tile.texts) v.setTextViewText(text,mode.short)
                v.setViewVisibility(tile.label,if(labels) View.VISIBLE else View.GONE)
                v.setContentDescription(tile.id,mode.label+(if(applying) ", applying" else if(on) ", selected" else "")+if(away) ", earbuds not connected" else "")
                if(interactive) {
                    val flags=PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE
                    val action=if(Prefs.deviceAddress(ctx)==null || !Headphones.hasPermission(ctx)) {
                        val setup=Intent(ctx,MainActivity::class.java).putExtra("hush.mode",mode.name)
                        PendingIntent.getActivity(ctx,mode.ordinal,setup,flags)
                    } else {
                        val set=Intent(ctx,ModeWidget::class.java).setAction(ACTION_SET).putExtra(EXTRA_MODE,mode.name)
                        PendingIntent.getBroadcast(ctx,mode.ordinal,set,flags)
                    }
                    v.setOnClickPendingIntent(tile.id,action)
                }
            }
        }

        /**
         * Lock-screen hub and large home slots: name and status, the listening time beside three
         * battery rings, and the mode group, all from cached state. Sizes come from
         * [WidgetLayout.dashboard]; the big number takes the largest size that fits its column.
         */
        private fun dashboard(ctx:Context,spec:WidgetLayout.DashboardSpec,current:SonyProtocol.Mode?,pending:SonyProtocol.Mode?,
                              interactive:Boolean,linked:Boolean?,last:Pair<SonyProtocol.Battery,Long>?):RemoteViews {
            val v=RemoteViews(ctx.packageName,R.layout.widget_dashboard)
            val away=linked==false
            val b=last?.first
            v.setTextViewText(R.id.w_title,Prefs.displayName(ctx) ?: Prefs.deviceName(ctx) ?: "WF-1000XM5")
            val status=AmbientTimer.until(ctx)?.let{"Back to ${AmbientTimer.returnMode(ctx).short} at "+android.text.format.DateFormat.getTimeFormat(ctx).format(java.util.Date(it))}
                ?: BatteryWidget.status(ctx,b,last?.second ?: 0L,linked,Prefs.lastSeen(ctx))
            v.setTextViewText(R.id.w_status,status)

            // The big number: how long you can listen; the case adds the second line.
            val rate=Prefs.drainRate(ctx,current)
            val buds=b?.let{BatteryLife.budsMinutes(it,current,rate)}
            val case=b?.let{BatteryLife.caseMinutes(it,current,rate)}?.takeIf{it>=10}
            val hero=buds?.let{BatteryLife.short(it)} ?: (current?.label ?: "Earbuds")
            v.setTextViewText(R.id.w_hero,hero)
            v.setTextColor(R.id.w_hero,ctx.getColor(if(buds!=null && buds<60) R.color.w_low else R.color.w_off_text))
            val heroSp=(32 downTo 18 step 2).firstOrNull{Widgets.textWidth(ctx,hero,it.toFloat(),"google-sans-medium")<=spec.heroWidth} ?: 18
            v.setTextViewTextSize(R.id.w_hero,TypedValue.COMPLEX_UNIT_SP,heroSp.toFloat())
            // Without a reading the header already says what to do; the big text names the mode.
            v.setTextViewText(R.id.w_hero_sub,"of listening")
            v.setViewVisibility(R.id.w_hero_sub,if(buds!=null) View.VISIBLE else View.GONE)
            v.setTextViewText(R.id.w_estimate,case?.let{"Case adds "+BatteryLife.short(it)} ?: "")
            v.setViewVisibility(R.id.w_estimate,if(spec.estimate && case!=null) View.VISIBLE else View.GONE)

            val bb=b ?: SonyProtocol.Battery()
            val spoken=listOf(
                BatteryWidget.bindRing(ctx,v,R.id.w_left_box,R.id.w_left_ring,R.id.w_left_art,R.id.w_left_value,R.id.w_left_label,R.id.w_left_charge,"Left",bb.left,bb.leftCharging,spec.ring,false),
                BatteryWidget.bindRing(ctx,v,R.id.w_case_box,R.id.w_case_ring,R.id.w_case_art,R.id.w_case_value,R.id.w_case_label,R.id.w_case_charge,"Case",bb.case,bb.caseCharging,spec.ring,false),
                BatteryWidget.bindRing(ctx,v,R.id.w_right_box,R.id.w_right_ring,R.id.w_right_art,R.id.w_right_value,R.id.w_right_label,R.id.w_right_charge,"Right",bb.right,bb.rightCharging,spec.ring,false),
            )
            v.setContentDescription(R.id.w_batteries,(buds?.let{"$hero of listening. "} ?: "")+"Battery: "+spoken.joinToString(", "))
            v.setViewLayoutHeight(R.id.w_modes,spec.modes,TypedValue.COMPLEX_UNIT_DIP)
            bindTiles(ctx,v,current,pending,away,spec.labels,24f,interactive)
            if(interactive) {
                val open=Intent(ctx,MainActivity::class.java).setFlags(Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP)
                val openApp=PendingIntent.getActivity(ctx,101,open,PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_IMMUTABLE)
                v.setOnClickPendingIntent(R.id.w_header,openApp)
                v.setOnClickPendingIntent(R.id.w_batteries,openApp)
            }
            return v
        }
    }
}
