"""Generates the splash icon (drawable/splash_icon.xml): the launcher icon itself, animated.

    python3 docs/icon/splash.py

Android shows the launcher icon in its circle when an app starts; Google's apps animate that very
icon for a moment and then hand over to the app. So does this one, in 650 ms: the case's lid pops
up a little on its hinge and clicks shut with a small spring, and the status light blinks and sends
out one soft ring. First and last frames are exactly the launcher icon (ic_launcher_foreground on
its white background). SplashHandoff then lays the icon's circle onto Home's case ring.
"""
import re
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res"
fg = (RES / "drawable/ic_launcher_foreground.xml").read_text()
paths = re.findall(r"<path\b[^>]*/>|<path\b[^>]*[^/]>.*?</path>", fg, flags=re.S)
lid, body, led = paths  # generated in this order by google_style.py
led = led.replace("<path ", '<path android:name="led" ', 1)

TOTAL = 650
DECEL = "@interpolator/w_emphasized"
SPRING = "@interpolator/splash_spring"
LINEAR = "@android:interpolator/linear"


def track(prop, *keys):
    """One animator per property over the whole icon animation: (ms, value[, interpolator])."""
    frames = "".join(
        f'<keyframe android:fraction="{k[0] / TOTAL:.3f}" android:value="{k[1]}"'
        + (f' android:interpolator="{k[2]}"' if len(k) > 2 else "") + "/>"
        for k in keys)
    return (f'<objectAnimator android:duration="{TOTAL}" android:interpolator="{LINEAR}">'
            f'<propertyValuesHolder android:propertyName="{prop}" android:valueType="floatType">{frames}</propertyValuesHolder>'
            f'</objectAnimator>')


def target(name, *animators):
    return (f'    <target android:name="{name}"><aapt:attr name="android:animation"><set>\n        '
            + "\n        ".join(animators) + "\n    </set></aapt:attr></target>\n")


ring = ('<group android:name="pulse" android:pivotX="54" android:pivotY="60.5">'
        '<path android:name="pulse_ring" android:strokeColor="#34A853" android:strokeWidth="1" android:strokeAlpha="0" '
        'android:pathData="M51.4,60.5 a2.6,2.6 0 1,0 5.2,0 a2.6,2.6 0 1,0 -5.2,0 Z"/></group>')

xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by docs/icon/splash.py from ic_launcher_foreground.xml; edit the script. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
            <group android:name="case" android:pivotX="54" android:pivotY="71">
                <group android:name="lid" android:pivotX="78" android:pivotY="50.5">
                    {lid}
                </group>
                {body}
                {led}
                {ring}
            </group>
        </vector>
    </aapt:attr>
""" + target("lid",
             # up on its hinge (the back right corner, as seen), then shut with a small overshoot
             track("rotation", (0, 0), (60, 0), (260, 9, DECEL), (300, 9), (470, 0, SPRING), (650, 0)),
             track("translateY", (0, 0), (60, 0), (260, -2.6, DECEL), (300, -2.6), (470, 0, SPRING), (650, 0))) \
    + target("case",
             # the body answers the click: a tiny squash as the lid lands
             track("scaleY", (0, 1), (440, 1), (500, 0.97), (600, 1, SPRING), (650, 1)),
             track("scaleX", (0, 1), (440, 1), (500, 1.015), (600, 1, SPRING), (650, 1))) \
    + target("led", track("fillAlpha", (0, 1), (240, 1), (300, 0.25), (380, 1, DECEL), (650, 1))) \
    + target("pulse", track("scaleX", (0, 1), (380, 1), (650, 3.4, DECEL)), track("scaleY", (0, 1), (380, 1), (650, 3.4, DECEL))) \
    + target("pulse_ring", track("strokeAlpha", (0, 0), (380, 0), (400, 0.9), (650, 0, DECEL))) \
    + "</animated-vector>\n"
(RES / "drawable/splash_icon.xml").write_text(xml)
