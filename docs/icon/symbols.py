"""Widget and notification icons from the app's own Material Symbols font.

    pip install fonttools
    python3 docs/icon/symbols.py

The app draws its icons from res/font/material_symbols.ttf (Material Symbols Rounded, subset to
the glyphs it uses, with the FILL and wght axes kept), so fill and weight can animate. Widgets and
notifications need plain vector drawables; this writes them from the same font at weight 400,
and at weight 600 for the chosen mode ("_bold"), so every surface shows exactly the same icon.
These three symbols have no filled form; elsewhere FILL 1 swaps in drawn filled glyphs.
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

RES = Path(__file__).resolve().parents[2] / "app/src/main/res"
FONT = RES / "font/material_symbols.ttf"
ICONS = {  # drawable name: Material Symbols codepoint
    "w_icon_anc": 0xF8A8,      # noise_control_on
    "w_icon_ambient": 0xE023,  # hearing
    "w_icon_off": 0xEBF3,      # noise_control_off
    "w_icon_earbuds": 0xF003,  # earbuds: the widget's open-the-app button
}
GLYPH_KOTLIN = RES.parent / "java/ua/olex/sonyanc/ModeGlyphPaths.kt"
HEADER = "<!-- Generated by docs/icon/symbols.py from res/font/material_symbols.ttf; edit the script. -->"


def filled_name(font: TTFont, name: str) -> str:
    """At FILL 1 the font swaps many glyphs for drawn filled ones (GSUB rclt, feature variations)."""
    for lookup in font["GSUB"].table.LookupList.Lookup:
        if lookup.LookupType == 1:
            for sub in lookup.SubTable:
                if name in sub.mapping:
                    return sub.mapping[name]
    return name


def path_of(font: TTFont, codepoint: int, filled: bool) -> str:
    glyphs = font.getGlyphSet()
    name = font.getBestCmap()[codepoint]
    if filled:
        name = filled_name(font, name)
    pen = SVGPathPen(glyphs, lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
    glyphs[name].draw(pen)
    return pen.getCommands()


def main():
    for fill, weight, suffix in ((0, 400, ""), (0, 600, "_bold")):
        font = instantiateVariableFont(TTFont(FONT), {"FILL": fill, "wght": weight})
        for name, cp in ICONS.items():
            # Font units: 960 per em, baseline at y 0, y up. The group flips it into a 960 viewport.
            (RES / f"drawable/{name}{suffix}.xml").write_text(
                f'<?xml version="1.0" encoding="utf-8"?>\n{HEADER}\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp"\n'
                '    android:viewportWidth="960" android:viewportHeight="960">\n'
                '    <group android:scaleY="-1" android:translateY="960">\n'
                f'        <path android:fillColor="#FFFFFFFF" android:pathData="{path_of(font, cp, fill == 1)}" />\n'
                "    </group>\n</vector>\n"
            )

    # The dock interpolates the same outlines between regular and selected weights.
    lines = ["// Generated by docs/icon/symbols.py.", "package ua.olex.sonyanc", "", "internal object ModeGlyphPaths {"]
    for weight, suffix in ((400, "Regular"), (600, "Bold")):
        font = instantiateVariableFont(TTFont(FONT), {"FILL": 0, "wght": weight})
        for mode in ("anc", "ambient", "off"):
            contours = path_of(font, ICONS[f"w_icon_{mode}"], False).split("M")[1:]
            lines.append(f"    val {mode}{suffix} = listOf(")
            lines.extend(f'        "M{contour}",' for contour in contours)
            lines.append("    )")
    lines.append("}")
    GLYPH_KOTLIN.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
