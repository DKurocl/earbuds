"""The WF-1000XM5 as the app shows it, from one accurate render (docs/icon/ref/wf1000xm5_render.webp:
the left earbud and the closed case, front views, on transparency).

    pip install numpy pillow scipy potracer
    python3 docs/icon/device_pictures.py

Two kinds of picture, as on a Pixel:
  * device details (Home's battery rings, Device info): the render itself, as Android shows a
    Fast Pair device: drawable-nodpi/device_bud_left.webp, device_bud_right.webp (its mirror),
    device_case.webp;
  * small one-tint marks (widgets, notifications, the case tile): silhouettes traced from the same
    render: w_glyph_bud_left/right.xml (shell, the foam tip apart by a gap, the grille cut out) and
    ic_case_mark.xml (the case, its seam cut through, the status light a hole).
"""
import math
from pathlib import Path

import numpy as np
import potrace
from PIL import Image, ImageDraw, ImageFilter
from scipy import ndimage

ROOT = Path(__file__).resolve().parents[2]
RENDER = ROOT / "docs/icon/ref/wf1000xm5_render.webp"
NODPI = ROOT / "app/src/main/res/drawable-nodpi"
DRAW = ROOT / "app/src/main/res/drawable"
HEAD = "<!-- Generated by docs/icon/device_pictures.py from the WF-1000XM5 render; edit the script. -->"


def objects():
    im = Image.open(RENDER).convert("RGBA")
    a = np.asarray(im)
    fg = a[..., 3] > 20
    lab, n = ndimage.label(ndimage.binary_closing(fg, iterations=3))
    sizes = ndimage.sum(fg, lab, range(1, n + 1))
    parts = []
    for k in np.argsort(sizes)[::-1][:2] + 1:
        ys, xs = np.nonzero(lab == k)
        parts.append((xs.min(), ys.min(), xs.max() + 1, ys.max() + 1))
    bud, case = sorted(parts)  # the earbud is on the left
    return im, bud, case


def save_webp(img, name, longest):
    k = longest / max(img.size)
    img = img.resize((round(img.width * k), round(img.height * k)), Image.LANCZOS)
    img.save(NODPI / f"{name}.webp", "WEBP", quality=92, method=6)


def traced(m):
    """A mask to a path in a 24-unit viewport, 1-unit margin, centred."""
    m = np.pad(m, 16)  # potrace frames a mask that touches the border; keep it clear of it
    h, w = m.shape
    ys, xs = np.nonzero(m)
    x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
    scale = 22.0 / max(x1 - x0, y1 - y0)
    ox = 1 + (22 - (x1 - x0) * scale) / 2 - x0 * scale
    oy = 1 + (22 - (y1 - y0) * scale) / 2 - y0 * scale
    parts = []
    for c in potrace.Bitmap(m).trace(turdsize=60, alphamax=1.1, opticurve=True, opttolerance=0.6):
        xs_ = [c.start_point.x] + [s.end_point.x for s in c.segments]
        if min(xs_) < 1 and max(xs_) > w - 1:
            continue  # the bitmap's own frame
        p = lambda q: f"{q.x * scale + ox:.2f},{q.y * scale + oy:.2f}"
        seg = [f"M{p(c.start_point)}"]
        for s in c.segments:
            seg.append(f"L{p(s.c)} L{p(s.end_point)}" if s.is_corner else f"C{p(s.c1)} {p(s.c2)} {p(s.end_point)}")
        parts.append(" ".join(seg) + "Z")
    return " ".join(parts)


def glyph(d, comment, mirror=False):
    path = f'<path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="{d}"/>'
    group = '<group android:pivotX="12" android:scaleX="-1">' if mirror else "<group>"
    return (f'<?xml version="1.0" encoding="utf-8"?>\n{HEAD}\n<!-- {comment} -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:tools="http://schemas.android.com/tools"\n'
            '    android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24"\n'
            f'    tools:ignore="VectorPath">\n    {group}{path}</group>\n</vector>\n')


def smooth(m, r):
    return np.asarray(Image.fromarray((m * 255).astype("uint8")).filter(ImageFilter.GaussianBlur(r))) > 127


def main():
    im, bud_box, case_box = objects()
    bud = im.crop(bud_box)
    case = im.crop(case_box)
    NODPI.mkdir(parents=True, exist_ok=True)
    save_webp(bud, "device_bud_left", 384)
    save_webp(bud.transpose(Image.FLIP_LEFT_RIGHT), "device_bud_right", 384)
    save_webp(case, "device_case", 480)

    # ---- the earbud's mark ----
    a = np.asarray(bud).astype(int)
    shape = a[..., 3] > 128
    lum = a[..., 0] * 0.3 + a[..., 1] * 0.59 + a[..., 2] * 0.11
    w = shape.shape[1]
    gold = shape & (a[..., 0] - a[..., 2] > 22) & (lum < 200)
    # the foam tip and the dark ring under it: the dark part of the earbud's inner side
    tip = shape & (lum < 165) & ~gold & (np.mgrid[0:shape.shape[0], 0:w][1] > w * 0.55)
    lab, n = ndimage.label(tip)
    tip = lab == (np.argmax(ndimage.sum(tip, lab, range(1, n + 1))) + 1)
    tip = ndimage.binary_fill_holes(ndimage.binary_closing(tip, iterations=4))
    shell = shape & ~ndimage.binary_dilation(tip, iterations=1)
    lab, n = ndimage.label(shell)
    shell = ndimage.binary_fill_holes(lab == (np.argmax(ndimage.sum(shell, lab, range(1, n + 1))) + 1))
    gap = ndimage.binary_dilation(shell, iterations=max(2, int(w * 0.025)))
    mark = smooth(shell, 2) | smooth(tip & ~gap, 2)
    ys, xs = np.nonzero(gold)
    gx, gy, gr = xs.mean(), ys.mean(), math.sqrt(gold.sum() / math.pi) * 1.1
    m = Image.fromarray((mark * 255).astype("uint8"))
    ImageDraw.Draw(m).ellipse([gx - gr, gy - gr, gx + gr, gy + gr], fill=0)
    d = traced(np.asarray(m) > 127)
    DRAW.joinpath("w_glyph_bud_left.xml").write_text(glyph(d, "A WF-1000XM5 earbud as a one-tint mark (widgets, notifications): shell, foam tip apart, grille cut out. Tinted by its user."))
    DRAW.joinpath("w_glyph_bud_right.xml").write_text(glyph(d, "The right earbud: the left one mirrored. Tinted by its user.", mirror=True))

    # ---- the case's mark ----
    a = np.asarray(case).astype(int)
    shape = a[..., 3] > 128
    lum = a[..., 0] * 0.3 + a[..., 1] * 0.59 + a[..., 2] * 0.11
    h, w = shape.shape
    # the seam: the darkest row through the middle third, in the upper two thirds
    band = lum[:, int(w * 0.35):int(w * 0.65)].mean(1)
    rows = range(int(h * 0.25), int(h * 0.7))
    seam = min(rows, key=lambda r: band[r])
    # the status light: the darkest spot just under the seam, in the middle
    region = lum[seam + 5:seam + int(h * 0.25), int(w * 0.4):int(w * 0.6)]
    ly, lx = np.unravel_index(np.argmin(region), region.shape)
    ly += seam + 5; lx += int(w * 0.4)
    mark = shape.copy()
    t = max(2, int(h * 0.018))
    mark[seam - t:seam + t + 1, :] = False
    m = Image.fromarray((smooth(mark, 1.5) * 255).astype("uint8"))
    r = max(3, int(w * 0.018))
    ImageDraw.Draw(m).ellipse([lx - r, ly - r, lx + r, ly + r], fill=0)
    DRAW.joinpath("ic_case_mark.xml").write_text(glyph(traced(np.asarray(m) > 127),
        "The WF-1000XM5 case as a one-tint mark (widgets, notifications, the case tile): its outline, the seam cut through, the light a hole."))
    print("seam row", seam, "of", h, "light", lx, ly)


if __name__ == "__main__":
    main()
