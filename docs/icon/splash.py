"""Generates the animated splash icon (drawable/splash_icon.xml) from the launcher foreground.

    python3 docs/icon/splash.py

The same case as the launcher icon (docs/icon/google_style.py), animated for Android's splash
screen in under a second: the case springs in, the lid lifts as if opening and settles, and the
status light comes on. Values follow Material motion: emphasized decelerate for arrival, a short
overshoot for the lid.
"""
import re
from pathlib import Path

RES = Path(__file__).resolve().parents[2] / "app/src/main/res"
fg = (RES / "drawable/ic_launcher_foreground.xml").read_text()
# A path is either self-closing or holds a gradient (whose items are self-closing themselves).
paths = re.findall(r"<path\b[^>]*/>|<path\b[^>]*[^/]>.*?</path>", fg, flags=re.S)
lid, body, led = paths  # generated in this order
led = led.replace("<path ", "<path android:name=\"led\" android:fillAlpha=\"0\" ", 1)

xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by docs/icon/splash.py from ic_launcher_foreground.xml; edit the script. -->
<animated-vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt">
    <aapt:attr name="android:drawable">
        <vector android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
            <group android:name="case" android:pivotX="54" android:pivotY="54" android:scaleX="0.6" android:scaleY="0.6">
                <group android:name="lid" android:pivotX="30" android:pivotY="50.5">
                    {lid}
                </group>
                {body}
                {led}
            </group>
        </vector>
    </aapt:attr>
    <target android:name="case">
        <aapt:attr name="android:animation">
            <set>
                <objectAnimator android:propertyName="scaleX" android:valueFrom="0.6" android:valueTo="1" android:duration="420"
                    android:interpolator="@android:interpolator/overshoot" />
                <objectAnimator android:propertyName="scaleY" android:valueFrom="0.6" android:valueTo="1" android:duration="420"
                    android:interpolator="@android:interpolator/overshoot" />
            </set>
        </aapt:attr>
    </target>
    <target android:name="lid">
        <aapt:attr name="android:animation">
            <set android:ordering="sequentially">
                <objectAnimator android:propertyName="translateY" android:valueFrom="0" android:valueTo="-5" android:duration="220"
                    android:startOffset="300" android:interpolator="@android:interpolator/fast_out_slow_in" />
                <objectAnimator android:propertyName="translateY" android:valueFrom="-5" android:valueTo="0" android:duration="260"
                    android:interpolator="@android:interpolator/overshoot" />
            </set>
        </aapt:attr>
    </target>
    <target android:name="led">
        <aapt:attr name="android:animation">
            <objectAnimator android:propertyName="fillAlpha" android:valueFrom="0" android:valueTo="1" android:duration="160"
                android:startOffset="520" />
        </aapt:attr>
    </target>
</animated-vector>
'''
(RES / "drawable/splash_icon.xml").write_text(xml)
